import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const appRoot = path.resolve(import.meta.dirname, '..');
const projectRoot = path.resolve(appRoot, '..');
const loaderRoot = path.join(projectRoot, 'loader');
const version = JSON.parse(fs.readFileSync(path.join(appRoot, 'package.json'), 'utf8')).version;
const repository = 'Anyno001/Immersive-Galgame-System-AnyNo001';
const assetFile = `https://cdn.jsdelivr.net/gh/${repository}@v${version}/app/dist/igs.bundle.js`;

const bundlePath = path.join(appRoot, 'dist/igs.bundle.js');
const cssPath = path.join(appRoot, 'dist/igs.bundle.css');
const loaderPath = path.join(loaderRoot, 'igs-loader.js');
const loaderJsonPath = path.join(loaderRoot, 'igs-loader.json');
for (const file of [bundlePath, cssPath, loaderPath, loaderJsonPath]) {
    if (!fs.existsSync(file)) throw new Error(`本地包缺少构建产物：${file}`);
}

const bundle = fs.readFileSync(bundlePath, 'utf8');
if (!bundle.startsWith('// Generated by app/scripts/build.js.')) {
    throw new Error('igs.bundle.js 缺少构建文件头。');
}
if (bundle.includes('翻牌配对') || bundle.includes('这句是谁说的') || bundle.includes('心情猜猜')) {
    throw new Error('主体 bundle 仍包含等待小游戏。');
}
const assetHits = bundle.split('import.meta.url').length - 1;
if (!assetHits) throw new Error('主体 bundle 没有可改写的素材地址。');
const embeddedScript = bundle.replaceAll('import.meta.url', JSON.stringify(assetFile));
if (embeddedScript.includes('import.meta.url')) throw new Error('素材地址没有全部改写到固定版本。');

const css = fs.readFileSync(cssPath, 'utf8').replace(/url\((['"]?)(\.\/[^'")]+)\1\)/g, (_match, quote, relative) => {
    return `url(${quote}${new URL(relative, assetFile).href}${quote})`;
});
if (/url\((['"]?)\.\//.test(css)) throw new Error('样式里还有相对地址。');

const fingerprint = crypto.createHash('sha256').update(embeddedScript).digest('hex').slice(0, 16);
const localConfig = {
    ref: `local-v${version}-${fingerprint}`,
    base: `https://cdn.jsdelivr.net/gh/${repository}@v${version}/app/dist`,
    version,
    locked: true,
    cacheBust: false,
    hasCustomBase: true,
    latestRef: null,
    latestFromCache: false,
    localBundle: true,
};

const loader = fs.readFileSync(loaderPath, 'utf8');
const strictHeader = "(function () {\n    'use strict';\n";
if (!loader.startsWith(strictHeader)) throw new Error('loader 文件头和本地包生成器不一致。');
const cssUrl = `data:text/css;charset=utf-8;base64,${Buffer.from(css).toString('base64')}`;
// replace 的字符串替换会把 $& 当成匹配内容。bundle 里的正则转义含有 $&，必须用函数返回原文。
let content = loader.replace(strictHeader, () => `${strictHeader}\n    const LOCAL_BUNDLE_SOURCE = ${JSON.stringify(embeddedScript)};\n    const LOCAL_CSS_URL = ${JSON.stringify(cssUrl)};\n    const LOCAL_LOADER_CONFIG = ${JSON.stringify(localConfig)};\n`);

const loadLocalBundle = `
    async function loadLocalBundle(config) {
        const Url = root.URL || globalThis.URL;
        const BlobType = root.Blob || globalThis.Blob;
        let blobUrl = '';
        try {
            blobUrl = Url.createObjectURL(new BlobType([LOCAL_BUNDLE_SOURCE], { type: 'text/javascript' }));
            injectCss(LOCAL_CSS_URL);
            await injectScript(blobUrl, config.version);
            root[INSTANCE_KEY] = {
                repository: REPOSITORY, loadedAt: Date.now(), status: 'ready', reused: false,
                activeRef: config.ref, activeBase: config.base,
                version: (root.IGS || root.ImmersiveGalgameSystem).version,
                source: 'local-import',
            };
            scheduleMagicWandEnsure();
            schedulePendingQrOpen();
            console.info('[IGS Loader] 使用本地内置程序。', config.ref);
            return config;
        } finally {
            if (blobUrl) Url.revokeObjectURL(blobUrl);
        }
    }

`;
const loadMarker = '    async function load(config) {\n        if (config.embeddedRuntime) return loadEmbeddedRuntime(config);';
const configMarker = '    async function resolveLoaderConfig() {\n        const userConfig = getObject(root.IGS_LOADER_CONFIG);';
if (!content.includes(loadMarker) || !content.includes(configMarker)) {
    throw new Error('loader 源码变了，本地包生成器对不上。');
}
content = content.replace(loadMarker, () => `${loadLocalBundle}    async function load(config) {\n        if (config.localBundle) return loadLocalBundle(config);\n        if (config.embeddedRuntime) return loadEmbeddedRuntime(config);`);
content = content.replace(configMarker, () => '    async function resolveLoaderConfig() {\n        return LOCAL_LOADER_CONFIG;\n        const userConfig = getObject(root.IGS_LOADER_CONFIG);');

const published = JSON.parse(fs.readFileSync(loaderJsonPath, 'utf8'));
const outputName = `沉浸式Galgame系统 v${version} 本地测试.json`;
const outputPath = path.join(loaderRoot, outputName);
const localJson = {
    type: 'script',
    enabled: false,
    name: `沉浸式Galgame系统 v${version}（本地测试）`,
    id: `igs-local-test-${version.replaceAll('.', '')}`,
    content,
    info: [
        `内置 v${version} 当前本地 JS 和 CSS，程序指纹 ${fingerprint}。不下载远程程序或自动更新。`,
        `字体、默认背景等静态素材使用已发布 v${version} CDN。`,
        '等待小游戏已从主体拆出。需要游戏时再导入并启用同版本的「等待小游戏」脚本。',
    ].join('\n'),
    button: published.button,
    data: {},
    export_with: published.export_with,
};
fs.writeFileSync(outputPath, `${JSON.stringify(localJson, null, 2)}\n`, 'utf8');
const verify = JSON.parse(fs.readFileSync(outputPath, 'utf8'));
if (verify.content !== content || !verify.content.includes(fingerprint)) {
    throw new Error('本地测试 JSON 回读不一致。');
}
const syntaxPath = path.join(os.tmpdir(), `igs-local-${fingerprint}.js`);
fs.writeFileSync(syntaxPath, content);
const check = spawnSync(process.execPath, ['--check', syntaxPath], { encoding: 'utf8' });
fs.rmSync(syntaxPath, { force: true });
if (check.status !== 0) {
    throw new Error(`本地包语法检查失败：${check.stderr || check.stdout}`);
}
console.log(`local-package ok ${path.relative(projectRoot, outputPath)} ${fingerprint}`);
