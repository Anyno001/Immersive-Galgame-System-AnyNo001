import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { deflateSync } from 'node:zlib';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const appRoot = path.resolve(import.meta.dirname, '..');
const defaultProjectRoot = path.resolve(appRoot, '..');
export const ASSET_REF = '073e715a7b285f22f8d591a1da8286586564f969';
export const ASSET_BASE = 'https://cdn.jsdelivr.net/gh/Anyno001/IGS_GaLSystem@' + ASSET_REF;
export const importNameOf = version => `IGS-Live2D-导入即用-v${version}.json`;
const hash = text => createHash('sha256').update(text).digest('hex');

export function absolutizeCss(style, distBase) {
    return style.replace(/url\(\s*(['"]?)([^'"\s)]+)\1\s*\)/g, (whole, quote, value) => {
        if (/^(?:data:|blob:|https?:|\/\/|#)/i.test(value)) return whole;
        return 'url(' + JSON.stringify(new URL(value, distBase).href) + ')';
    });
}

export function embedRuntime({ script, style, version, assetBase = ASSET_BASE }) {
    const header = /^\/\/ Generated by app\/scripts\/build\.js\.[^\n]*\n\/\/ IGS version: (\d+\.\d+\.\d+)\r?\n/.exec(script)?.[1];
    if (!header || header !== version) throw new Error('Dist bundle header/version does not match package.json. Run npm run build first.');
    if (!/^https:\/\//.test(assetBase)) throw new Error('Standalone asset base must be a public HTTPS URL.');
    const distBase = assetBase.replace(/\/+$/, '') + '/app/dist/';
    return { version, script: script.replace(/\bimport\.meta\.url\b/g, JSON.stringify(distBase + 'igs.bundle.js')),
        style: absolutizeCss(style, distBase) };
}

export async function buildStandalone({ projectRoot = defaultProjectRoot, write = true } = {}) {
    const dist = path.join(projectRoot, 'app', 'dist');
    const loaderRoot = path.join(projectRoot, 'loader');
    const version = JSON.parse(fs.readFileSync(path.join(projectRoot, 'app', 'package.json'), 'utf8')).version;
    const script = fs.readFileSync(path.join(dist, 'igs.bundle.js'), 'utf8');
    const style = fs.readFileSync(path.join(dist, 'igs.bundle.css'), 'utf8');
    const loader = fs.readFileSync(path.join(loaderRoot, 'igs-loader.js'), 'utf8');
    const payload = embedRuntime({ script, style, version });
    const compressed = deflateSync(Buffer.from(JSON.stringify(payload)), { level: 9 }).toString('base64');
    // fflate 只打入同步解压/UTF-8 解码；不依赖浏览器 DecompressionStream 或外部解压 CDN。
    const codec = await build({
        stdin: { contents: "import { unzlibSync, strFromU8 } from 'fflate'; export function decode(text) { const bin = atob(text); const bytes = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i); return strFromU8(unzlibSync(bytes)); }", resolveDir: path.join(projectRoot, 'app') },
        write: false, bundle: true, minify: true, format: 'iife', globalName: '__IgsEmbeddedCodec',
        platform: 'browser', target: 'es2020', legalComments: 'inline',
    });
    const runtimeId = hash(JSON.stringify(payload) + loader).slice(0, 24);
    const license = fs.readFileSync(path.join(dist, 'fflate.LICENSE.txt'), 'utf8');
    const content = [
        '// IGS Live2D standalone. Frontend is embedded; no localhost service or remote frontend download.',
        '/* fflate 0.8.2 (MIT)\n' + license.replace(/\*\//g, '* /') + '\n*/',
        '(function () {', "'use strict';", codec.outputFiles[0].text,
        'var root = window;', 'try { if (window.parent && window.parent.document) root = window.parent; } catch (_) {}',
        'try {', 'var payload = JSON.parse(__IgsEmbeddedCodec.decode(' + JSON.stringify(compressed) + '));',
        'root.IGS_LOADER_CONFIG = { ref: ' + JSON.stringify('embedded-live2d-' + runtimeId) + ', base: ' + JSON.stringify(ASSET_BASE) + ', cacheBust: false, embeddedRuntime: payload };',
        loader,
        '} catch (error) { console.error("[IGS Live2D] 内嵌包读取失败", error); if (typeof root.alert === "function") root.alert("Live2D 脚本不完整或已损坏，请重新导入导入即用 JSON。" + (error && error.message || error)); }',
        '})();', '',
    ].join('\n');
    const scriptImport = {
        type: 'script', enabled: false, name: '沉浸式Galgame系统 + Live2D（导入即用） v' + version,
        id: 'e1410d07-3a4d-485c-8e04-4244ac5c777e', content,
        info: ['IGS ' + version + ' / Live2D standalone.1（本地适配，非上游官方发布）。',
            '前端与样式已内嵌：导入并启用即可，不需要 Node.js、CMD 或 18086 服务。',
            '先停用所有旧 Gal/Live2D 脚本并刷新，再启用本脚本；不要同时启用多份。',
            'BGM、字体、背景等原版素材按需从固定上游提交联网加载；Live2D SDK 也需要网络。',
            '模型入口：设置 → 角色 → 角色 → Live2D 角色模型；先开启「启用场景素材模式」并保存设置。模型仍需自行导入。',
            '此包固定内嵌适配版，不跟随官方 main 自动更新。升级时重新导入新版 JSON。',
            'fflate 0.8.2 MIT license:\n' + license].join('\n'),
        button: { enabled: true, buttons: [{ name: 'Gal模拟', visible: true }] },
        data: {}, export_with: { data: true, button: true },
    };
    const json = JSON.stringify(scriptImport, null, 2) + '\n';
    const manifest = { version, distribution: 'standalone.1', assetRef: ASSET_REF, assetBase: ASSET_BASE,
        runtimeId, sourceBundleSha256: hash(script), sourceCssSha256: hash(style), loaderSha256: hash(loader),
        contentSha256: hash(content), importSha256: hash(json), importBytes: Buffer.byteLength(json),
        embeddedRuntimeBytes: Buffer.byteLength(JSON.stringify(payload)), compressedBase64Bytes: compressed.length };
    if (write) {
        fs.writeFileSync(path.join(loaderRoot, 'igs-live2d-standalone.js'), content, 'utf8');
        fs.writeFileSync(path.join(loaderRoot, importNameOf(version)), json, 'utf8');
        fs.writeFileSync(path.join(loaderRoot, 'igs-live2d-standalone.manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');
    }
    return { content, scriptImport, json, manifest };
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
    const result = await buildStandalone();
    console.log('standalone:build ok ' + JSON.stringify(result.manifest));
}
