// Rebuild the small, source-local ZIP adapter used by the existing IGS module bundler.
import fs from 'node:fs';
import path from 'node:path';
import * as esbuild from 'esbuild';
const app = path.resolve(import.meta.dirname, '..');
const result = await esbuild.build({ stdin: { contents: "export { unzipSync, zipSync } from 'fflate';", resolveDir: app, sourcefile: 'live2d-zip-entry.js' }, bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2020', legalComments: 'inline' });
const dir = path.join(app, 'src/vendor'); fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'fflate.js'), '// fflate 0.8.2, MIT (see fflate.LICENSE.txt). Generated by scripts/vendor-live2d-zip.mjs.\n' + result.outputFiles[0].text.replace(/^\/\/ .*fflate\/esm\/browser\.js$/m, '// fflate/esm/browser.js'));
fs.copyFileSync(path.join(app, 'node_modules/fflate/LICENSE'), path.join(dir, 'fflate.LICENSE.txt'));
console.log('Live2D ZIP adapter generated (fflate 0.8.2)');
