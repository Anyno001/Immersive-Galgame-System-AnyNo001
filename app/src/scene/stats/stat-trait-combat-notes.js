function bText(name) {
    for (const [cat, names, note = ''] of B_GROUPS) {
        if (names.includes(name)) return '奖励里' + cat + '牌更常出现' + note;
    }
    return '';
}

const NAMES = new Set([...Object.keys(A), ...Object.keys(C), ...Object.keys(COMBO), ...B_GROUPS.flatMap((g) => g[1])]);

// 单个特质的说明；没有对应战斗效果时返回空串。命中多类时用「；」合成一句。
export function traitCombatNote(name) {
    const key = String(name || '');
    if (!NAMES.has(key)) return '';
    const parts = [A[key], bText(key), C[key], COMBO[key]].filter(Boolean);
    return parts.length ? '卡牌战斗：' + parts.join('；') : '';
}

export const TRAIT_COMBAT_NOTE_NAMES = Object.freeze([...NAMES]);
