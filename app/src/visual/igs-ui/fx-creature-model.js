// 非人角色标注的提示词：只说明写法，不含物种词库；开关跟随战斗演出（readerSettings.battleFx.enabled）。

export function resolveCreatureFxPromptRule(enabled) {
    if (enabled !== true) return '';
    return `【非人角色】非人角色（妖魔鬼怪、怪物、使魔、坐骑、Boss）首次出场或体型变化时，写一次 [igs-fx:creature|名字|形态|体型|落地]：

1. 形态写 半人形（兽人、人鱼、魔物娘等）或 非人（完全非人形）
2. 体型写 小型／中型／大型／巨型
3. 落地写 落地 或 悬浮
4. 后三栏可省略，省略时按 非人／中型／落地

语法要求：
1. 已有人类角色不标注，同一角色体型未变化时不重复标注
2. 战斗对手若是首次出现的怪物，宜在开战前用本指令标注体型`;
}

