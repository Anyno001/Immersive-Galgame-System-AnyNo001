// 牌面关键字标记（describeEffectParts 的 kw 键）：status:键 取状态注释，res:键 取资源注释。
export function markTip(key) {
    if (key.startsWith('status:')) return STATUS_TIPS[key.slice(7)];
    if (key.startsWith('res:')) return RESOURCE_TIPS[key.slice(4)];
    return undefined;
}

// 单位状态片的属性：data-status 与悬停注释（标题用面板显示名与当前层数，机制说明取 STATUS_TIPS）；没有注释的状态只带 data-status。
export function statusTipText(s) {
    const tip = STATUS_TIPS[s?.key];
    return tip ? `${s.label} ${s.stacks} 层：${tip.slice(tip.indexOf('：') + 1)}` : '';
}
