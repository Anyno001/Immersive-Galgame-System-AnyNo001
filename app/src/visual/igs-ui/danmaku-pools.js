// 由字符串得到稳定的伪随机数，用于人气基数等「同一主播每次都一样」的数值。
export function stableHash(value) {
    let hash = 2166136261;
    for (const ch of String(value || '')) {
        hash ^= ch.codePointAt(0);
        hash = Math.imul(hash, 16777619);
    }
    return hash >>> 0;
}

