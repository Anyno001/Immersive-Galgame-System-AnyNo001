const f = (list) => Object.freeze(list.slice());

// 主播这句话是怎么说的：结巴 / 笑 / 哭 / 提问 / 喊 / 很短。按顺序判，先中先用。
const SAY_FORMS = Object.freeze([
    ['hesitate', /(\S)、\1|……|\.\.\.|欲言又止|那个……|就是……/],
    ['laugh', /哈哈|嘿嘿|噗|呵呵|嘻嘻/],
    ['cry', /呜|哭|泪|哽咽/],
    ['question', /[？?]\s*[”"」』]?\s*$|吗[。？?]?[”"」』]?\s*$|是不是|要不要|好不好|对吧|对不对/],
    ['exclaim', /[！!]\s*[”"」』]?\s*$/],
]);
const SHORT_SAY = 4;

export function classifySayForm(said) {
    const text = String(said == null ? '' : said).trim();
    if (!text) return '';
    const hit = SAY_FORMS.find(([, re]) => re.test(text));
    if (hit) return hit[0];
    return Array.from(text.replace(/[\s，。！？、…“”"「」]/g, '')).length <= SHORT_SAY ? 'short' : '';
}

