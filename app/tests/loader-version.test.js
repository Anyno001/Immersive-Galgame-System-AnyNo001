import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const source = fs.readFileSync(new URL('../../loader/igs-loader.js', import.meta.url), 'utf8');
const localSource = fs.readFileSync(new URL('../../loader/igs-live2d-local.js', import.meta.url), 'utf8');
const localImport = JSON.parse(fs.readFileSync(new URL('../../loader/IGS-Live2D-本地测试.json', import.meta.url), 'utf8'));
const version = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;
const ref = `v${version}`;
const fixedContent = source.replace("const PINNED_REF = '';", `const PINNED_REF = ${JSON.stringify(ref)};`);
const autoContent = JSON.parse(fs.readFileSync(new URL('../../loader/igs-loader.json', import.meta.url), 'utf8')).content;
const base = `https://cdn.jsdelivr.net/gh/Anyno001/Immersive-Galgame-System-AnyNo001@${ref}`;
const instanceKey = '__IGS_AUTO_UPDATE_LOADER__';
const settle = async () => { for (let i = 0; i < 6; i++) await new Promise(resolve => setImmediate(resolve)); };

function harness({ oldVersion, oldRef, shutdown, servedVersion = version, probeStatus = 200, scriptError = false, cdnError = false, rawBody, auto = false, local = false, contentOverride } = {}) {
    const nodes = new Map(), scripts = [], requests = [], alerts = [], logs = [], timers = [];
    const blobs = [], revoked = [], cleared = [], subscriptions = [];
    let stopped = 0, ensured = 0, opened = 0;
    const root = {
        AbortController, Blob,
        URL: {
            createObjectURL: blob => { blobs.push(blob); return `blob:igs-${blobs.length}`; },
            revokeObjectURL: url => revoked.push(url),
        },
        setTimeout: (callback, ms) => { timers.push({ callback, ms }); return timers.length; },
        clearTimeout: id => cleared.push(id),
        addEventListener() {}, removeEventListener() {},
        alert: message => alerts.push(message),
        eventOn: (_event, handler) => { subscriptions.push(handler); return {}; }, getButtonEvent: name => name,
        localStorage: { getItem: () => null, setItem() {}, removeItem() {} },
        fetch: async (url, options) => {
            requests.push({ url, options });
            return { ok: probeStatus === 200, status: probeStatus,
                json: async () => ({ commit: { sha: 'b'.repeat(40) } }),
                text: async () => rawBody ?? `// Generated by app/scripts/build.js. Do not edit this file directly.\n// IGS version: ${servedVersion}\nconst resource = new URL('./voice/a.mp3', import.meta.url);`,
            };
        },
    };
    function api(apiVersion) {
        return { version: apiVersion, openSettings: () => ({}), openLatestAvailable: () => { opened++; return { ok: true }; },
            ensureMagicWandEntry: () => { ensured++; return { ok: true }; },
            async shutdown() { stopped++; if (shutdown) return shutdown(); return { ok: true }; } };
    }
    const doc = {
        querySelector: selector => selector.startsWith('#') ? nodes.get(selector.slice(1)) || null : null,
        querySelectorAll: () => [],
        createElement: tag => ({ tagName: tag, remove() { if (nodes.get(this.id) === this) nodes.delete(this.id); } }),
        head: { appendChild(node) {
            nodes.set(node.id, node);
            if (node.tagName !== 'script') return;
            scripts.push(node.src);
            queueMicrotask(() => {
                if (scriptError || (cdnError && !node.src.startsWith('blob:'))) { node.onerror?.(); return; }
                root.IGS = root.ImmersiveGalgameSystem = api(servedVersion);
                node.onload?.();
            });
        } },
    };
    root.document = doc; root.parent = root; root.top = root;
    if (oldVersion) root.IGS = root.ImmersiveGalgameSystem = api(oldVersion);
    if (oldRef) root[instanceKey] = { repository: 'Anyno001/Immersive-Galgame-System-AnyNo001', activeRef: oldRef,
        activeBase: `https://cdn.jsdelivr.net/gh/Anyno001/Immersive-Galgame-System-AnyNo001@${oldRef}` };
    const quiet = { info: (...args) => logs.push(args), warn: (...args) => logs.push(args), error: (...args) => logs.push(args) };
    const context = vm.createContext({ window: root, document: doc, console: quiet, Promise, Date, atob, Uint8Array, TextDecoder });
    const content = contentOverride ?? (local ? localSource : auto ? autoContent : fixedContent);
    return { root, nodes, scripts, requests, alerts, logs, timers, blobs, revoked, cleared, run: () => vm.runInContext(content, context), click: () => subscriptions[0](), opened: () => opened, stopped: () => stopped, ensured: () => ensured };
}

test('gate:loader:auto-import-file-matches-source-without-requiring-a-new-tag', () => {
    assert.equal(autoContent, source);
});

test('gate:loader:pinned-version-replaces-a-fully-working-older-runtime', async () => {
    const f = harness({ oldVersion: '0.36.59' });
    f.run(); await settle();
    assert.equal(f.stopped(), 1);
    assert.equal(f.root.IGS.version, version);
    assert.equal(f.scripts.length, 1);
    assert.equal(f.root[instanceKey].activeRef, ref);
    assert.ok(f.scripts.every(url => url.startsWith(`${base}/`)));
    assert.deepEqual(f.alerts, []);
});

test('gate:loader:matching-version-with-unknown-source-must-reload-the-tag', async () => {
    const f = harness({ oldVersion: version });
    f.run(); await settle();
    assert.equal(f.stopped(), 1); assert.equal(f.scripts.length, 1);
});

test('gate:loader:matching-version-from-main-cannot-substitute-for-a-fixed-tag', async () => {
    const f = harness({ oldVersion: version, oldRef: 'main' });
    f.run(); await settle();
    assert.equal(f.stopped(), 1); assert.equal(f.root[instanceKey].activeRef, ref);
});
