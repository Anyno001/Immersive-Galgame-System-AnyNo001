import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { embedRuntime, absolutizeCss, buildStandalone, ASSET_BASE } from '../scripts/build-standalone.js';
const version = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;
const header = '// Generated by app/scripts/build.js. Do not edit this file directly.\n// IGS version: 0.36.75\n';

test('standalone:asset-rewrite-preserves-nonrelative-urls', () => {
    const css = '@import url("./fonts/a/font.css?v=123");a{background:url(./skins/a.png)}b{background:url(data:image/png;base64,AA)}c{mask:url(#a)}d{background:url(https://other.invalid/a)}';
    const rewritten = absolutizeCss(css, ASSET_BASE + '/app/dist/');
    assert.ok(rewritten.includes(ASSET_BASE + '/app/dist/fonts/a/font.css?v=123'));
    assert.ok(rewritten.includes(ASSET_BASE + '/app/dist/skins/a.png'));
    assert.ok(rewritten.includes('url(data:image/png;base64,AA)'));
    assert.ok(rewritten.includes('url(#a)'));
    assert.ok(rewritten.includes('url(https://other.invalid/a)'));
});

test('standalone:bundle-asset-base-is-fixed-without-using-blob-or-tavern-origin', () => {
    const result = embedRuntime({ script: header + "export const image = new URL('./backgrounds/a.webp', import.meta.url);", style: '', version: '0.36.75' });
    assert.ok(!result.script.includes('import.meta.url'));
    assert.ok(result.script.includes(ASSET_BASE + '/app/dist/igs.bundle.js'));
    assert.throws(() => embedRuntime({ script: header, style: '', version: '0.0.1' }), /header\/version/);
    assert.throws(() => embedRuntime({ script: header, style: '', version: '0.36.75', assetBase: 'http://127.0.0.1:18086' }), /public HTTPS/);
});

test('standalone:generated-package-is-deterministic-and-dist-exact', async () => {
    const result = await buildStandalone({ write: false });
    const source = fs.readFileSync(new URL('../../loader/igs-live2d-standalone.js', import.meta.url), 'utf8');
    const json = fs.readFileSync(new URL(`../../loader/IGS-Live2D-导入即用-v${version}.json`, import.meta.url), 'utf8');
    assert.equal(result.content, source);
    assert.equal(result.json, json);
    assert.equal(result.manifest.version, version);
    assert.ok(result.manifest.importBytes < 3 * 1024 * 1024);
    assert.equal(result.scriptImport.content, source);
});
